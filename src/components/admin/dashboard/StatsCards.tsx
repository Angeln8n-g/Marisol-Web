import React from 'react'

interface StatCard {
  label: string
  value: string | number
  icon: React.ReactNode
  color: string
  onClick?: () => void
}

interface StatsCardsProps {
  stats: StatCard[]
  isLoading?: boolean
}

export const StatsCards: React.FC<StatsCardsProps> = ({ stats, isLoading = false }) => {
  if (isLoading) {
    return (
      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4">
        {[...Array(4)].map((_, i) => (
          <div key={i} className="bg-white rounded-lg border border-gray-200 p-5 animate-pulse">
            <div className="h-4 w-24 bg-gray-200 rounded mb-3" />
            <div className="h-8 w-16 bg-gray-200 rounded" />
          </div>
        ))}
      </div>
    )
  }

  return (
    <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4">
      {stats.map((stat) => (
        <div
          key={stat.label}
          onClick={stat.onClick}
          className={`rounded-lg border p-5 ${stat.color} transition-colors ${
            stat.onClick ? 'cursor-pointer hover:shadow-md active:scale-[0.98]' : ''
          }`}
          role={stat.onClick ? 'button' : undefined}
          tabIndex={stat.onClick ? 0 : undefined}
          onKeyDown={stat.onClick ? (e) => { if (e.key === 'Enter' || e.key === ' ') stat.onClick?.() } : undefined}
        >
          <div className="flex items-center justify-between mb-2">
            <p className="text-sm font-montserrat opacity-80">{stat.label}</p>
            <div className="opacity-60">{stat.icon}</div>
          </div>
          <p className="text-3xl font-playfair font-bold">{stat.value}</p>
        </div>
      ))}
    </div>
  )
}

